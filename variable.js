// let means the value can change later
// const means the value cannot change

let x = 3;
let y = 5;
let z = x + y;

console.log(z); // output: 8

let variable = "hello world";
console.log(variable);

let name = "rafi";
const country = "Bangladesh";

console.log(name);

name = "Rahim"; // you can reassign a value
console.log(name);

// country = "India"; you cannot reassign a value to a constant variable
console.log(country);
